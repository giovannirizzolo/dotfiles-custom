#!/usr/bin/env bash
# Paint the tmux statusline with the active Ghostty theme.
#
# Reads the theme Ghostty uses (current-theme.ghostty written by the fish
# `ghostty_theme` picker, else `theme =` in config.ghostty), fills the
# @@ROLE@@ placeholders in statusline.tmpl.conf, writes statusline.theme.conf
# and sources it into the running tmux server.
# Run by tmux.conf on start/reload and by `ghostty_theme` on every switch.
set -euo pipefail

TMUX_DIR="$HOME/.config/tmux"
GHOSTTY_DIR="$HOME/.config/ghostty"
BUILTIN_DIR="/Applications/Ghostty.app/Contents/Resources/ghostty/themes"
TEMPLATE="$TMUX_DIR/statusline.tmpl.conf"
OUT="$TMUX_DIR/statusline.theme.conf"

theme_setting() { # theme = "..." from a Ghostty config file
  [ -f "$1" ] || return 0
  sed -nE 's/^[[:space:]]*theme[[:space:]]*=[[:space:]]*"?([^"]*)"?[[:space:]]*$/\1/p' "$1" | head -1
}

name=${GHOSTTY_THEME_FILE:-}
[ -n "$name" ] || name=$(theme_setting "$GHOSTTY_DIR/current-theme.ghostty")
[ -n "$name" ] || name=$(theme_setting "$GHOSTTY_DIR/config.ghostty")
theme=""
[[ "$name" == "~/"* ]] && name="$HOME/${name#\~/}"
if [[ "$name" == /* ]]; then
  theme=$name
else
  for d in "$GHOSTTY_DIR/themes" "$BUILTIN_DIR"; do
    [ -f "$d/$name" ] && { theme="$d/$name"; break; }
  done
fi
if [ ! -f "$theme" ]; then
  echo "ghostty-theme.sh: can't find Ghostty theme '$name'" >&2
  exit 1
fi

key() { # exact key lookup -> lowercase #rrggbb
  sed -nE "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*#?([0-9a-fA-F]{6}).*/#\1/p" "$theme" | head -1 | tr 'A-F' 'a-f'
}
pal() {
  sed -nE "s/^[[:space:]]*palette[[:space:]]*=[[:space:]]*$1[[:space:]]*=[[:space:]]*#?([0-9a-fA-F]{6}).*/#\1/p" "$theme" | head -1 | tr 'A-F' 'a-f'
}
mix() { # mix a b amount(0-100) -> hex
  local a=${1#\#} b=${2#\#} t=$3 out="#" i
  for i in 0 2 4; do
    local x=$((16#${a:i:2})) y=$((16#${b:i:2}))
    out+=$(printf '%02x' $(((x * (100 - t) + y * t + 50) / 100)))
  done
  echo "$out"
}

C=()
for i in $(seq 0 15); do C[$i]=$(pal "$i"); done
BG=$(key background); FG=$(key foreground)
SEL=$(key selection-background); [ -n "$SEL" ] || SEL=$(mix "$BG" "$FG" 20)
ACCENT=$(key cursor-color); [ -n "$ACCENT" ] || ACCENT=${C[11]}
ACCENT2=${C[1]}; [ "$ACCENT2" != "$ACCENT" ] || ACCENT2=${C[5]}
DIM=$(mix "${C[8]}" "${C[7]}" 50)

args=(-e "s/@@BG@@/$BG/g" -e "s/@@FG@@/$FG/g" -e "s/@@SEL@@/$SEL/g"
      -e "s/@@ACCENT2@@/$ACCENT2/g" -e "s/@@ACCENT@@/$ACCENT/g" -e "s/@@DIM@@/$DIM/g")
for i in $(seq 15 -1 0); do args+=(-e "s/@@C$i@@/${C[$i]}/g"); done
{
  echo "# GENERATED by ghostty-theme.sh from $(basename "$theme") — edit statusline.tmpl.conf"
  sed "${args[@]}" "$TEMPLATE"
} >"$OUT.tmp" && mv "$OUT.tmp" "$OUT"

if grep -v "^#" "$OUT" | grep -q "@@"; then
  echo "ghostty-theme.sh: unfilled placeholder in $OUT" >&2
  exit 1
fi

# Apply to the running server (no-op when tmux isn't running).
[ -n "${GHOSTTY_TMUX_NO_APPLY:-}" ] || tmux source-file "$OUT" 2>/dev/null || true
